export const INGREDIENT_ICON = 32;

/**
 * Figma 986:2 : l'image de l'ingrédient devant sa ligne. Sans image connue, ou si elle ne se charge pas, l'icône
 * générique dessinée pour Toqué prend sa place.
 */
export function IngredientIcon({ ingredient }: { ingredient: Ingredient }) {
  const source = ingredientImageOf(ingredient);
  const [failed, setFailed] = useState(false);
  if (!source || failed) return <GenericIngredient />;
  return (
    <Image
      source={source}
      style={styles.image}
      resizeMode="contain"
      onError={() => setFailed(true)}
      accessibilityIgnoresInvertColors
    />
  );
}

